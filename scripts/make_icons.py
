import os
from PIL import Image, ImageDraw

def generate_gamers_id_icon():
    size = 512
    img = Image.new("RGBA", (size, size), (11, 14, 20, 255))
    
    circle_img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    center = (256, 256)
    radius = 150
    
    # Outer Glow
    glow_draw = ImageDraw.Draw(img)
    for r in range(radius + 24, radius, -2):
        alpha = int(25 * (1 - (r - radius) / 24))
        glow_draw.ellipse(
            [center[0] - r, center[1] - r, center[0] + r, center[1] + r],
            fill=(56, 189, 248, alpha)
        )

    # Gradient Circle (Cyan -> Orange)
    for y in range(center[1] - radius, center[1] + radius):
        for x in range(center[0] - radius, center[0] + radius):
            dx = x - center[0]
            dy = y - center[1]
            if dx*dx + dy*dy <= radius*radius:
                factor = ((x - (center[0] - radius)) + (y - (center[1] - radius))) / (radius * 4)
                factor = max(0.0, min(1.0, factor))
                r_col = int(56 + (255 - 56) * factor)
                g_col = int(189 + (138 - 189) * factor)
                b_col = int(248 + (0 - 248) * factor)
                circle_img.putpixel((x, y), (r_col, g_col, b_col, 255))

    img.alpha_composite(circle_img)

    # White Controller
    draw = ImageDraw.Draw(img)
    cx, cy = 256, 256

    draw.rounded_rectangle([cx - 85, cy - 48, cx + 85, cy + 48], radius=28, fill=(255, 255, 255, 255))
    draw.ellipse([cx - 82, cy + 10, cx - 40, cy + 58], fill=(255, 255, 255, 255))
    draw.ellipse([cx + 40, cy + 10, cx + 82, cy + 58], fill=(255, 255, 255, 255))
    draw.ellipse([cx - 32, cy + 28, cx + 32, cy + 68], fill=(220, 110, 0, 255))

    # D-Pad
    dpad_x, dpad_y = cx - 44, cy - 2
    draw.rounded_rectangle([dpad_x - 5, dpad_y - 18, dpad_x + 5, dpad_y + 18], radius=2, fill=(30, 41, 59, 255))
    draw.rounded_rectangle([dpad_x - 18, dpad_y - 5, dpad_x + 18, dpad_y + 5], radius=2, fill=(30, 41, 59, 255))

    # Action Buttons
    btn_x, btn_y = cx + 44, cy - 2
    btn_r = 5
    draw.ellipse([btn_x - btn_r, btn_y - 14 - btn_r, btn_x + btn_r, btn_y - 14 + btn_r], fill=(30, 41, 59, 255))
    draw.ellipse([btn_x - btn_r, btn_y + 14 - btn_r, btn_x + btn_r, btn_y + 14 + btn_r], fill=(30, 41, 59, 255))
    draw.ellipse([btn_x - 14 - btn_r, btn_y - btn_r, btn_x - 14 + btn_r, btn_y + btn_r], fill=(30, 41, 59, 255))
    draw.ellipse([btn_x + 14 - btn_r, btn_y - btn_r, btn_x + 14 + btn_r, btn_y + btn_r], fill=(30, 41, 59, 255))

    os.makedirs("assets/images", exist_ok=True)
    img.save("assets/images/app_icon.png", format="PNG")

    # Android mipmap icons replacement
    android_sizes = {
        "mipmap-mdpi": 48,
        "mipmap-hdpi": 72,
        "mipmap-xhdpi": 96,
        "mipmap-xxhdpi": 144,
        "mipmap-xxxhdpi": 192,
    }

    base_res = "android/app/src/main/res"
    if os.path.exists(base_res):
        for folder, px in android_sizes.items():
            folder_path = os.path.join(base_res, folder)
            os.makedirs(folder_path, exist_ok=True)
            resized = img.resize((px, px), Image.Resampling.LANCZOS)
            resized.save(os.path.join(folder_path, "ic_launcher.png"), format="PNG")

if __name__ == "__main__":
    generate_gamers_id_icon()
