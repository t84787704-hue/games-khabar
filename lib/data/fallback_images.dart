/// Universal image finder that guarantees every single card gets a high quality game picture.
/// Checks title, category, and content keywords before falling back to the universal gamer default.
String getGameFallbackImage({
  String? category,
  String? title,
  String? content,
}) {
  final cleanTitle = (title ?? '').toUpperCase();
  final cleanCat = (category ?? '').toUpperCase().trim();
  final cleanContent = (content ?? '').toUpperCase();

  // 1. Check title keywords first (most specific)
  for (final entry in gameFallbackImages.entries) {
    if (entry.key == 'DEFAULT' || entry.key == 'TRENDING' || entry.key == 'MOBILE' || entry.key == 'PC' || entry.key == 'CONSOLE') {
      continue;
    }
    if (cleanTitle.contains(entry.key)) {
      return entry.value;
    }
  }

  // 2. Check category matching
  for (final entry in gameFallbackImages.entries) {
    if (cleanCat.contains(entry.key) || entry.key.contains(cleanCat)) {
      return entry.value;
    }
  }

  // 3. Check content keywords
  for (final entry in gameFallbackImages.entries) {
    if (entry.key == 'DEFAULT' || entry.key == 'TRENDING' || entry.key == 'MOBILE' || entry.key == 'PC' || entry.key == 'CONSOLE') {
      continue;
    }
    if (cleanContent.contains(entry.key)) {
      return entry.value;
    }
  }

  // 4. Default to universal high-octane gaming artwork
  return gameFallbackImages['DEFAULT']!;
}
